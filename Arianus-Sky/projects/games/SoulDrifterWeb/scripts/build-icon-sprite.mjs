/**
 * Builds the creator's Lucide sprite from exactly the names in `src/creationIcons.ts`.
 *
 * Every name must have a file in the pinned `lucide-static`; a missing icon throws so the
 * build fails instead of shipping a blank `<use>`. Writes `public/assets/icons/soul-icons.svg`
 * and, when `index.html` carries a `<!-- soul-icons:start -->` / `<!-- soul-icons:end -->`
 * block, rewrites the symbols inline there so phones make no extra request. Run via
 * `npm run icons`; `npm run build` runs it before `vite build`.
 */

import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { ICON_NAMES, ICON_SYMBOL_PREFIX } from "../src/creationIcons.ts";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lucideRoot = resolve(projectRoot, "node_modules/lucide-static");
const lucideIconsDir = resolve(lucideRoot, "icons");
const spritePath = resolve(projectRoot, "public/assets/icons/soul-icons.svg");
const licensePath = resolve(projectRoot, "public/assets/icons/LICENSE-lucide.txt");
const indexPath = resolve(projectRoot, "index.html");

export const SPRITE_BLOCK_START = "<!-- soul-icons:start -->";
export const SPRITE_BLOCK_END = "<!-- soul-icons:end -->";
const ICON_VIEW_BOX = "0 0 24 24";

/** Reads one Lucide file and returns its inner markup (the paths, without the outer `<svg>`). */
async function readIconMarkup(name, iconsDir) {
  const path = resolve(iconsDir, `${name}.svg`);
  let source;
  try {
    source = await readFile(path, "utf8");
  } catch (error) {
    if (error && error.code === "ENOENT") return null;
    throw error;
  }
  const match = /<svg\b([^>]*)>([\s\S]*?)<\/svg>/.exec(source);
  if (!match) throw new Error(`Lucide icon "${name}" is not an SVG document: ${path}`);
  const viewBox = /viewBox="([^"]*)"/.exec(match[1])?.[1];
  if (viewBox !== ICON_VIEW_BOX) {
    throw new Error(`Lucide icon "${name}" has viewBox "${viewBox}", expected "${ICON_VIEW_BOX}".`);
  }
  const inner = match[2]
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
  if (inner.length === 0) throw new Error(`Lucide icon "${name}" has no drawable markup.`);
  return inner;
}

/**
 * Turns icon names into `<symbol>` markup, one per name, in the given order.
 * Throws when a name is duplicated or has no file in `iconsDir`.
 */
export async function buildSpriteSymbols(names, { iconsDir = lucideIconsDir, symbolPrefix = ICON_SYMBOL_PREFIX } = {}) {
  const seen = new Set();
  const duplicates = names.filter((name) => (seen.has(name) ? true : (seen.add(name), false)));
  if (duplicates.length > 0) {
    throw new Error(`ICON_NAMES lists these names more than once: ${[...new Set(duplicates)].join(", ")}`);
  }
  const symbols = [];
  const missing = [];
  for (const name of names) {
    const inner = await readIconMarkup(name, iconsDir);
    if (inner === null) {
      missing.push(name);
      continue;
    }
    symbols.push(
      [`<symbol id="${symbolPrefix}${name}" viewBox="${ICON_VIEW_BOX}">`, ...inner.map((line) => `  ${line}`), "</symbol>"].join("\n"),
    );
  }
  if (missing.length > 0) {
    throw new Error(
      `ICON_NAMES has no Lucide file for: ${missing.join(", ")} (looked in ${iconsDir}). ` +
        "Fix the name in src/creationIcons.ts; a missing icon must fail the build.",
    );
  }
  return symbols;
}

function indent(block, spaces) {
  const pad = " ".repeat(spaces);
  return block
    .split("\n")
    .map((line) => (line ? pad + line : line))
    .join("\n");
}

export function renderSpriteFile(symbols, version) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Lucide icons from lucide-static v${version} (ISC, see LICENSE-lucide.txt). Generated by scripts/build-icon-sprite.mjs; do not edit. -->`,
    '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">',
    "  <defs>",
    ...symbols.map((symbol) => indent(symbol, 4)),
    "  </defs>",
    "</svg>",
    "",
  ].join("\n");
}

/**
 * Replaces the markup between the sprite markers in an HTML document. Returns `null` when the
 * document has no block; throws when only one marker is present.
 */
export function replaceInlineSpriteBlock(html, symbols, version) {
  const start = html.indexOf(SPRITE_BLOCK_START);
  const end = html.indexOf(SPRITE_BLOCK_END);
  if (start === -1 && end === -1) return null;
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`index.html must carry both "${SPRITE_BLOCK_START}" and "${SPRITE_BLOCK_END}", in that order.`);
  }
  const lineStart = html.lastIndexOf("\n", start) + 1;
  const indentation = html.slice(lineStart, start).match(/^[ \t]*/)?.[0] ?? "";
  const block = [
    SPRITE_BLOCK_START,
    `<!-- lucide-static v${version}, ISC. Generated by scripts/build-icon-sprite.mjs; edit src/creationIcons.ts instead. -->`,
    ...symbols,
    SPRITE_BLOCK_END,
  ]
    .map((line) => indent(line, indentation.length))
    .join("\n")
    .trimStart();
  return html.slice(0, start) + block + html.slice(end + SPRITE_BLOCK_END.length);
}

async function readInstalledLucideVersion() {
  const pkg = JSON.parse(await readFile(resolve(lucideRoot, "package.json"), "utf8"));
  const pinned = JSON.parse(await readFile(resolve(projectRoot, "package.json"), "utf8")).devDependencies?.["lucide-static"];
  if (pkg.version !== pinned) {
    throw new Error(`Installed lucide-static ${pkg.version} does not match the package.json pin "${pinned}".`);
  }
  return pkg.version;
}

async function assertVendoredLicense(version) {
  let text;
  try {
    text = await readFile(licensePath, "utf8");
  } catch {
    throw new Error(`Missing vendored license ${licensePath}; copy node_modules/lucide-static/LICENSE with the version in its header.`);
  }
  if (!text.includes(`lucide-static v${version}`)) {
    throw new Error(`${licensePath} does not name lucide-static v${version} in its header; update the vendored license.`);
  }
}

export async function buildIconSprite() {
  const version = await readInstalledLucideVersion();
  await assertVendoredLicense(version);
  const symbols = await buildSpriteSymbols(ICON_NAMES);
  await mkdir(dirname(spritePath), { recursive: true });
  await writeFile(spritePath, renderSpriteFile(symbols, version), "utf8");
  const html = await readFile(indexPath, "utf8");
  const rewritten = replaceInlineSpriteBlock(html, symbols, version);
  if (rewritten !== null && rewritten !== html) await writeFile(indexPath, rewritten, "utf8");
  return { version, count: symbols.length, spritePath, inlined: rewritten !== null };
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const result = await buildIconSprite();
  const where = result.inlined ? "and inlined in index.html" : "(index.html carries no soul-icons block yet)";
  console.log(`soul-icons: ${result.count} Lucide ${result.version} symbols written to ${result.spritePath} ${where}`);
}
